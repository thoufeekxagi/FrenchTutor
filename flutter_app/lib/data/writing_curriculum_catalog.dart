/// Fast, offline writing practice for the first weeks of learning.
///
/// These are deliberately small tasks, not generated essays. They let a new
/// learner start immediately and give the Writing home a real progression:
/// choose a word, build a sentence, then write a short message. The live
/// generator remains an explicit action for a personalised task after the
/// learner has used the ready queue.
abstract final class WritingCurriculumCatalog {
  static List<WritingTask> forLevel(String level) {
    final band = level.trim().toUpperCase();
    if (band == 'A1') {
      return [..._a1, ..._foundationQueue(band)];
    }
    if (band == 'A2') {
      return [..._a2, ..._foundationQueue(band)];
    }
    return _advanced
        .where((task) => task.levelBand == band)
        .toList(growable: false);
  }

  /// Adds a large, deterministic offline queue for beginner practice. The
  /// existing authored rows stay first so any previously saved completion
  /// IDs remain valid; these rows extend the same queue without a network wait.
  static List<WritingTask> _foundationQueue(String band) {
    final lowerBand = band.toLowerCase();
    return [
      for (var index = 0; index < _writingWordSeeds.length; index++)
        _wordTask(lowerBand, band, index, _writingWordSeeds[index]),
      for (var index = 0; index < _writingSentenceSeeds.length; index++)
        _sentenceTask(lowerBand, band, index, _writingSentenceSeeds[index]),
      for (var index = 0; index < _writingFreeSeeds.length; index++)
        _freeWritingTask(lowerBand, band, index, _writingFreeSeeds[index]),
    ];
  }

  static WritingTask _wordTask(
    String lowerBand,
    String band,
    int index,
    _WritingWordSeed seed,
  ) {
    return WritingTask(
      id: 'write-$lowerBand-word-foundation-${index + 1}',
      type: 'word',
      levelBand: band,
      title: seed.title,
      titleEn: seed.english,
      promptFr: 'Complète avec le bon mot.',
      promptEn: 'Complete the phrase with the French word for ${seed.english}.',
      minWords: 1,
      wordBank: [seed.french, ...seed.distractors],
      targetTokens: [seed.french],
      targetConnectors: const [],
      rubricHints: ['Recognise one useful $band word.'],
    );
  }

  static WritingTask _sentenceTask(
    String lowerBand,
    String band,
    int index,
    _WritingSentenceSeed seed,
  ) {
    return WritingTask(
      id: 'write-$lowerBand-sentence-foundation-${index + 1}',
      type: 'sentence',
      levelBand: band,
      title: seed.title,
      titleEn: seed.english,
      promptFr: 'Construis la phrase.',
      promptEn: 'Put the French words in order to say: ${seed.english}.',
      minWords: seed.tokens.length,
      wordBank: [...seed.tokens, ...seed.distractors],
      targetTokens: seed.tokens,
      targetConnectors: const [],
      rubricHints: [seed.focus],
    );
  }

  static WritingTask _freeWritingTask(
    String lowerBand,
    String band,
    int index,
    _WritingFreeSeed seed,
  ) {
    return WritingTask(
      id: 'write-$lowerBand-free-foundation-${index + 1}',
      type: 'free_write',
      levelBand: band,
      title: seed.title,
      titleEn: seed.title,
      promptFr: seed.promptFr,
      promptEn: seed.promptEn,
      minWords: band == 'A1' ? 6 : 12,
      targetConnectors: const [],
      rubricHints: [seed.focus],
    );
  }

