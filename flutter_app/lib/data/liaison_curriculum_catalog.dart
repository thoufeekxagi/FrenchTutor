enum LiaisonRuleType { obligatory, forbidden, optional }

/// One frozen liaison lesson.
///
/// The catalog deliberately stores the spoken boundary separately from the
/// ordinary French spelling. Speech recognition can confirm [sentence], while
/// the audio evaluator receives [linkSound] and [ruleType] as the pronunciation
/// contract. This prevents a matching transcript from being misreported as a
/// matching liaison sound.
class LiaisonCurriculumLesson {
  const LiaisonCurriculumLesson({
    required this.id,
    required this.level,
    required this.collection,
    required this.title,
    required this.subtitle,
    required this.firstWord,
    required this.secondWord,
    required this.linkedDisplay,
    required this.soundHint,
    required this.linkSound,
    required this.ruleType,
    required this.explanation,
    required this.sentence,
    required this.sentenceEnglish,
    required this.passage,
    required this.passageEnglish,
  });

  final String id;
  final String level;
  final String collection;
  final String title;
  final String subtitle;
  final String firstWord;
  final String secondWord;
  final String linkedDisplay;
  final String soundHint;
  final String linkSound;
  final LiaisonRuleType ruleType;
  final String explanation;
  final String sentence;
  final String sentenceEnglish;
  final String passage;
  final String passageEnglish;

  String get phrase => '$firstWord $secondWord';
  String get progressId => 'liaison_curriculum_$id';
  bool get expectsLink => ruleType != LiaisonRuleType.forbidden;
  bool get requiresLink => ruleType == LiaisonRuleType.obligatory;
}

LiaisonCurriculumLesson _lesson({
  required String id,
  required String level,
  required String collection,
  required String title,
  required String subtitle,
  required String firstWord,
  required String secondWord,
  required String linkedDisplay,
  required String soundHint,
  required String linkSound,
  required LiaisonRuleType ruleType,
  required String explanation,
  required String sentence,
  required String sentenceEnglish,
  String? passage,
  String? passageEnglish,
}) => LiaisonCurriculumLesson(
  id: id,
  level: level,
  collection: collection,
  title: title,
  subtitle: subtitle,
  firstWord: firstWord,
  secondWord: secondWord,
  linkedDisplay: linkedDisplay,
  soundHint: soundHint,
  linkSound: linkSound,
  ruleType: ruleType,
  explanation: explanation,
  sentence: sentence,
  sentenceEnglish: sentenceEnglish,
  passage:
      passage ?? '$sentence Répétez la phrase une fois, sans faire de pause.',
  passageEnglish:
      passageEnglish ??
      '$sentenceEnglish Repeat the sentence once without pausing.',
);

