enum GrammarPracticeMode { pickWord, makeSentence, writeOwn }

/// Frozen, instant grammar curriculum used by the learner-facing Grammar home.
///
/// A1 and A2 are deliberately prebuilt so a beginner never waits for a model
/// before starting. B1 and B2 keep five reliable anchor lessons each; learners
/// can explicitly request more from the Grammar home when they want them.
class GrammarCurriculumLesson {
  const GrammarCurriculumLesson({
    required this.id,
    required this.level,
    required this.collection,
    required this.title,
    required this.subtitle,
    required this.tip,
    required this.pickPrompt,
    required this.pickChoices,
    required this.pickAnswer,
    required this.sentence,
    required this.translation,
    required this.incorrectSentence,
    required this.generationPoint,
  });

  final String id;
  final String level;
  final String collection;
  final String title;
  final String subtitle;
  final String tip;
  final String pickPrompt;
  final List<String> pickChoices;
  final String pickAnswer;
  final String sentence;
  final String translation;
  final String incorrectSentence;
  final String generationPoint;

  String get progressId => 'grammar_curriculum_$id';

  List<String> get sentenceTiles => sentence
      .replaceAll(RegExp(r'([,.!?;:])'), r' $1')
      .split(RegExp(r'\s+'))
      .where((token) => token.isNotEmpty)
      .toList(growable: false);

  String get writingPrompt =>
      'Write one new French sentence that uses ${pickAnswer.toLowerCase()} correctly.';
}

